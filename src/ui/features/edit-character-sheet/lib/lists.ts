/**
 * Список вводится строкой через запятую: отдельный редактор списка стоил бы своего экрана ради
 * данных, которые за всю игру правят однажды.
 *
 * Пустая строка даёт пустой список, а не список с пустой строкой: схема пустых имён не принимает.
 */
export function asList(text: string): string[] {
  return text
    .split(",")
    .map((part) => part.trim())
    .filter((part) => part !== "");
}
