/**
 * Время строки как «ЧЧ:ММ».
 *
 * Одно на все списки, где строка называет, когда это было: журнал и записи про мир показывают время
 * одинаково, и вторая запись формата разошлась бы с первой молча — на одном экране получилось бы
 * «9:05», на соседнем «09:05».
 *
 * Даты в строке нет: за столом спрашивают «когда сегодня», а дата стоила бы второй строки на самом
 * узком экране.
 */
export function timeRu(at: string): string {
  const moment = new Date(at);
  const hours = `${moment.getHours()}`.padStart(2, "0");
  const minutes = `${moment.getMinutes()}`.padStart(2, "0");
  return `${hours}:${minutes}`;
}
