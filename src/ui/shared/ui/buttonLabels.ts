/**
 * Слова, которыми отображение зовёт свои дела: чем набранное вступает в силу, чем уходит ни с чем и
 * чем зовётся дверь в правку записи.
 *
 * Живут они здесь, а не в компонентах: слово, набранное на месте, не сверяется ни с чем, и каждый
 * экран называет одно и то же дело своим глаголом. За столом на выбор между глаголами уходит
 * секунда, которой нет.
 *
 * Уход и возврат разведены нарочно: закрыть шторку и вернуть сделанное — разные дела, и общего
 * корня им не полагается.
 */

/**
 * Слово двери в правку записи: им шторка правки зовётся и снаружи, и внутри.
 *
 * Живёт рядом со словами кнопок по той же причине: дверь пишет один файл, шторку — другой, а читает
 * их за столом один человек, и два слова на одно дело он читает как два разных дела. Случившееся за
 * столом этим словом не зовётся — его подтверждают, а не сохраняют.
 */
export const EDIT_LABEL = "Правка";

/** Имя двери правки и имя её шторки: слово дела и запись, которой оно касается. */
export function editName(recordRu: string): string {
  return `${EDIT_LABEL}: ${recordRu}`;
}

export const BUTTON_LABELS = {
  /** Правится запись листа: повтор нажатия оставит её той же. */
  save: "Сохранить",
  /** Совершается событие за столом: сотворение, отдых, возврат ячеек, урон и лечение. */
  confirm: "Подтвердить",
  /** Уход, ничего не изменивший. */
  dismiss: "Отмена",
  /** Возврат сделанного: журнал возвращает записанное им же. */
  undo: "Вернуть",
} as const;
