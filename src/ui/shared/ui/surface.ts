/**
 * Ступени подложки: на чём лежит содержимое и чем окаймлено.
 *
 * Ступень отвечает на вопрос «что это такое»: страница, сгруппированное, нажимаемое или выехавшее
 * поверх. На вопрос «что это значит» отвечает тон, на вопрос «где кончается одно и начинается
 * другое» — линейка. Три разных вопроса, три разных владельца.
 *
 * Порядок ступеней меняется вместе с темой, роли — нет: на чернильной подложке нажимаемое
 * светлеет, на бумажной темнеет. Само правило живёт в значениях токенов, а не здесь.
 *
 * Край ступени неотделим от неё самой: на тёплой подложке соседние ступени различаются слабее,
 * чем волосяная линия, и ступень без края читалась бы как продолжение соседней. Сама линия
 * приходит от своего владельца — здесь она только приписана к ступени.
 */

import { RULE_ACTIVE, RULE_EDGE_TOP, RULE_GROUP } from "@/ui/shared/ui/rule";

/**
 * Страница: то, на чём лежит всё остальное.
 *
 * Её же носит полноэкранный вид — карточка, мастер, схема: он закрывает страницу целиком и потому
 * обязан выглядеть страницей, а не приподнятым над ней листом.
 */
export const SURFACE_PAGE = "bg-page";

/** Группа: раздел, карточка, плашка, шаг мастера. Ступень над страницей. */
export const SURFACE_GROUP = `bg-group ${RULE_GROUP}`;

/**
 * Та же ступень, но без своего края: его называет кто-то другой и не нейтральным цветом.
 *
 * Так стоит метка и нажатый переключатель: край у них говорит, какого значения эта метка, и
 * нейтральный край рядом с ним спорил бы за то же место.
 */
export const SURFACE_GROUP_BARE = "bg-group";

/**
 * Нажимаемое: кнопка, поле ввода, невыбранный переключатель. Ступень над группой.
 *
 * Палец метит в кнопку, а не в раздел вокруг неё, поэтому нажимаемое отходит от страницы дальше,
 * чем сгруппированное.
 */
export const SURFACE_CONTROL = `bg-control ${RULE_GROUP}`;

/**
 * Шторка, панель и закреплённая полоса — то, что лежит поверх содержимого.
 *
 * Тени у ступени нет: на тёмной тёплой подложке при слабом свете тень не читается вовсе, а её
 * край всё равно приходится отмечать линейкой. Поэтому у выехавшего своя ступень, а не заимствованная
 * ступень группы с тенью поверх.
 */
export const SURFACE_PANEL = `bg-sheet ${RULE_EDGE_TOP}`;

/**
 * Ступень недоступного нажимаемого: кнопка остаётся кнопкой, но перестаёт звать.
 *
 * Прозрачностью её гасить нельзя — падает контраст и подписи, и знака вместе с ней. Причину
 * недоступности при этом называет сама кнопка второй строкой: погашенное без причины читается как
 * поломка приложения.
 */
export const SURFACE_DISABLED = "disabled:bg-control";

/**
 * Главная кнопка: акцент под подписью цвета страницы.
 *
 * Белая подпись на золоте даёт 2.15 при требуемых 4.5 — на тёмной теме золото само по себе светлое.
 * Цвет страницы работает в обеих темах сразу: на золоте он тёмный, на бронзе светлый, и роль
 * «подпись главной кнопки» остаётся одна.
 */
export const SURFACE_PRIMARY = "bg-accent text-page";

/**
 * Выбранное: акцент обводит его и красит подпись.
 *
 * Отметку выбора не берут у смыслового тона. Синяя подложка выбранного варианта читается как
 * «действие», зелёная — как «ритуал», и выбор оказывается окрашен в чужое значение; хуже того,
 * подпись приходится красить тем же тоном, чтобы она читалась на подкраске, и порог контраста
 * начинает зависеть от того, что именно выбрали. Акцент значения не носит и потому годится: он
 * означает ровно «вот это», и означает это одинаково во всех восьми режимах.
 */
export const SURFACE_CHOSEN = `bg-group text-accent ${RULE_ACTIVE}`;
