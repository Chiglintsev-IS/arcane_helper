/**
 * Ступени подложки: структуру держит подложка, а не рамка.
 *
 * Живут рядом со смысловыми тонами и по той же причине: ими пользуются и примитивы, и карточки, и
 * экраны. Тон отвечает на вопрос «что это значит», ступень — на вопрос «что это такое»: страница,
 * сгруппированное или нажимаемое. Рамка не отвечает ни на один из них и потому занята ролью
 * заклинания — её владелец единственный.
 *
 * Ступеней три, а имён четыре: панель берёт ступень группы и добавляет к ней тень, потому что
 * лежит поверх содержимого. Четвёртой ступени не заводится — на тёмной теме она отличается от
 * третьей меньше, чем видно глазу, а на светлой её пришлось бы уводить в серый, который спорит
 * с подписями.
 */

/**
 * Страница: то, на чём лежит всё остальное.
 *
 * Её же носит полноэкранный вид — карточка, мастер, схема: он закрывает страницу целиком и потому
 * обязан выглядеть страницей, а не приподнятым над ней листом.
 */
export const SURFACE_PAGE = "bg-slate-100 dark:bg-slate-950";

/** Группа: раздел, карточка, плашка, шаг мастера. Ступень над страницей. */
export const SURFACE_GROUP = "bg-white shadow-sm dark:bg-slate-900 dark:shadow-none";

/**
 * Нажимаемое: кнопка, поле ввода, невыбранный переключатель. Ступень над группой.
 *
 * Палец метит в кнопку, а не в раздел вокруг неё, поэтому нажимаемое лежит выше сгруппированного, а
 * не вровень с ним.
 */
export const SURFACE_CONTROL = "bg-slate-200 dark:bg-slate-800";

/**
 * Шторка, панель и закреплённая полоса — то, что лежит поверх содержимого.
 *
 * Ступень та же, что у группы, но тень обязательна: шторка выезжает на страницу, и без тени её край
 * приходилось бы отмечать линией — то есть рамкой в том месте, где её быть не должно.
 */
export const SURFACE_PANEL = "bg-white shadow-lg dark:bg-slate-900";
