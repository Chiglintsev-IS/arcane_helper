/**
 * Линейки: чем отделено одно от другого.
 *
 * Структуру держит линейка, а не тень и не обводка всего подряд. Причина в подложке: на тёплой
 * чернильной странице при слабом свете соседние ступени различаются хуже, чем волосяная линия, а
 * тень не читается вовсе. Так устроена книга правил, и по той же причине: печать теней не знает.
 *
 * Владелец один на все линейки сразу, включая цветные. Линейка притягивает взгляд, и раздать её
 * каждому месту применения значит получить восемь толщин и четыре оттенка на одном экране; здесь
 * же видно весь набор целиком, и лишняя запись в нём заметна.
 *
 * Толщина отвечает за уровень: двойная открывает раздел, тройная слева называет роль строки или
 * отмечает выбранный блок, волосяная обводит блок и делит строки внутри него. Скругления в наборе нет вовсе — форма различается линейкой и ступенью
 * подложки, а не радиусом.
 */

import type { Tone } from "@/ui/shared/ui/tone";

/**
 * Двойная линейка акцентом: ею открывается раздел.
 *
 * Единственное место, где линейка стоит во всю ширину экрана, — под шапкой раздела. Двойная она
 * потому, что открывает не блок, а весь раздел: одинарная в этой позиции читалась бы как край
 * закреплённого.
 */
export const RULE_SECTION = "border-b-[3px] border-double border-accent";

/** Левая линейка смыслового блока: акцентом и толще прочих — ею блок и назван смысловым. */
export const RULE_BLOCK = "border-l-[3px] border-l-accent-rule";

/** Разделитель строк внутри блока: волосяная линия вместо отступа в полторы строки. */
export const RULE_ROW = "border-t border-rule";

/** Граница блока и всего нажимаемого: где кончается плитка и начинается страница. */
export const RULE_GROUP = "border border-rule-strong";

/**
 * Край закреплённого снизу: линия между тем, что уезжает, и тем, что стоит под ним.
 *
 * Она не обводит, а отмечает, что содержимое уходит под закреплённое, и потому стоит с одной
 * стороны.
 */
export const RULE_EDGE_TOP = "border-t border-rule-strong";

/**
 * Левая линейка строки, названная ролью заклинания.
 *
 * Роль перестала обводить карточку целиком: обводка теперь занята структурой, и цветная рамка
 * вокруг каждой строки списка читалась бы как ещё один уровень вложенности. Роль осталась цветом,
 * но с краю — и рядом с ней обязательны знак и слово, потому что цвет один смысла не несёт.
 *
 * «Ни то, ни другое» линейку получает нейтральную, а не пустую: строка без роли иначе стояла бы на
 * три пикселя уже соседней.
 */
export const RULE_ROLE: Record<Tone, string> = {
  action: "border-l-[3px] border-l-action",
  bonus: "border-l-[3px] border-l-bonus",
  reaction: "border-l-[3px] border-l-reaction",
  concentration: "border-l-[3px] border-l-concentration",
  ritual: "border-l-[3px] border-l-ritual",
  offense: "border-l-[3px] border-l-offense",
  defense: "border-l-[3px] border-l-defense",
  roll: "border-l-[3px] border-l-roll",
  muted: "border-l-[3px] border-l-rule-strong",
};


/** Акцент обводит выбранное: им отмечено то, что сейчас в силе. */
export const RULE_ACTIVE = "border border-accent";

/**
 * Обводка метки своим тоном: цвет держит край, а не заливку.
 *
 * Подкрашенная подложка меняла контраст подписи на ней, и подпись приходилось красить в тот же тон,
 * чтобы она читалась, — а тогда одно значение красило и знак, и слово, и фон под ними. Край
 * называет тон один раз, подпись остаётся чернилами, и порог контраста от тона больше не зависит.
 */
export const RULE_MARK: Record<Tone, string> = {
  action: "border border-action",
  bonus: "border border-bonus",
  reaction: "border border-reaction",
  concentration: "border border-concentration",
  ritual: "border border-ritual",
  offense: "border border-offense",
  defense: "border border-defense",
  roll: "border border-roll",
  muted: "border border-off",
};
