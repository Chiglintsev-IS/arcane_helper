/**
 * Режим экрана: в какой ситуации игрок открыл приложение.
 *
 * Это состояние интерфейса, а не правило игры: доменной схемы персонажа он не касается и в
 * сохранение не попадает. Выбор переживает перезапуск потому, что его держит оболочка, и значение,
 * которого нет в этом списке, читается ею как отсутствующее.
 *
 * Боя среди значений нет: идущий бой — состояние игры, отмечаемое в журнале, а не вкладка.
 */

export const SCREEN_MODES = ["play", "book", "journal", "sheet", "gear", "bag", "rest"] as const;

export type ScreenMode = (typeof SCREEN_MODES)[number];

/** За столом приложение чаще всего открывают, чтобы сходить. */
export const DEFAULT_SCREEN_MODE: ScreenMode = "play";
