/**
 * Глубокая неизменяемость: состояние, которое компилятор не даёт править на месте.
 *
 * «Менять только через корень агрегата» держалось дисциплиной, а дисциплина забывается: присваивание
 * в поле состояния собиралось молча и обходило и лог, и инварианты. Тип превращает это в отказ
 * сборки — там же, где написано, и до запуска.
 *
 * Разбор схемы отдаёт изменяемое: изменяемое присваивается неизменяемому без каста, и приведение к
 * состоянию остаётся честным. Обратно — только новым объектом, что и требуется.
 */

export type DeepReadonly<TValue> = TValue extends readonly (infer TItem)[]
  ? readonly DeepReadonly<TItem>[]
  : TValue extends object
    ? { readonly [TKey in keyof TValue]: DeepReadonly<TValue[TKey]> }
    : TValue;
