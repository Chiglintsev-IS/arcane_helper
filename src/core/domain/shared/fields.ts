/**
 * Поля значения, форма которого ещё не проверена.
 *
 * Приведение прежних сохранений и разбор прочитанного работают с данными, которые объявлений ещё не
 * проходили: ключи у них есть, а типов нет. Каждое поле приходит поэтому как `unknown` — узнать, что
 * в нём лежит, вправе только объявление. У значения, которое не объект, полей нет вовсе.
 */
export function fieldsOf(value: unknown): Record<string, unknown> {
  return value !== null && typeof value === "object" ? { ...value } : {};
}
