/**
 * Слова редкости: их называет стол, и говорят ими оба контекста — вещь помнит редкость раскрытого
 * свойства, ремесло по ней считает цену эффекта и надбавку исследования. Словарь общий, чтобы
 * записанное одним читалось другим; цены по этим словам — дело того, чей это ресурс.
 *
 * Порядок — от частого к редкому: им же идут строки справочника и кнопки выбора.
 */
export const RARITY_NAMES = [
  "Обычное",
  "Необычное",
  "Редкое",
  "Очень редкое",
  "Легендарное",
] as const;

export type RarityRu = (typeof RARITY_NAMES)[number];

/**
 * Редкость попутного свойства стол не называет — спрашивают про то, ради чего варят. Поэтому
 * неназванное оценивается по первой строке: она и есть самая обыкновенная.
 */
export const PLAINEST_RARITY: RarityRu = RARITY_NAMES[0];
