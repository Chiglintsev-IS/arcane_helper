/**
 * Лестница редкости: её называет стол, и говорят ею оба контекста — вещь помнит редкость
 * раскрытого свойства, ремесло по ней считает цену эффекта и надбавку исследования. Словарь общий,
 * чтобы записанное одним читалось другим; цены по этим словам — дело того, чей это ресурс.
 *
 * Порядок — от частого к редкому: им же идут строки справочника и кнопки выбора.
 */
export const RARITY_STEPS = [
  "Обычное",
  "Необычное",
  "Редкое",
  "Очень редкое",
  "Легендарное",
] as const;

export type RarityStepRu = (typeof RARITY_STEPS)[number];

/**
 * Особая редкость — то, что стол называет свойству мимо лестницы: строки в таблице за ней нет, и
 * цену такому свойству называет мастер, а не приложение. Она стоит последней: лестница кончается
 * там, где начинается воля стола.
 */
export const SPECIAL_RARITY = "Особое";

/** Все слова редкости, какими стол может пометить свойство: ступени лестницы и особая. */
export const RARITY_NAMES = [...RARITY_STEPS, SPECIAL_RARITY] as const;

/**
 * Редкость попутного свойства стол не называет — спрашивают про то, ради чего варят. Поэтому
 * неназванное оценивается по первой ступени: она и есть самая обыкновенная.
 */
export const PLAINEST_RARITY: RarityStepRu = RARITY_STEPS[0];
