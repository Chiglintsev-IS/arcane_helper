import { describe, expect, it } from "vitest";

import { z } from "zod";

import { parsedBySchema } from "./schema";

/**
 * Причина отказа синтетической схемы, собранная в одну строку — так же, как её собирают разбор
 * файла, разбор сообщения и объявления контекстов: все они входят через `parsedBySchema`.
 */
function refusalOf(schema: z.ZodType, value: unknown): string {
  const result = parsedBySchema(schema, value);
  if (result.success) throw new Error("схема приняла значение, а тест ждал отказа");
  return result.error.issues.map((issue) => issue.message).join("; ");
}

describe("причина отказа схемы — по-русски целиком (parsedBySchema)", () => {
  it("дробное число под .int() называет ожидаемый и полученный тип по-русски", () => {
    expect(refusalOf(z.number().int(), 1.5)).toBe(
      "Неверный ввод: ожидалось целое число, получено число",
    );
  });

  it("NaN под числовой схемой называет полученное «NaN», а не отвергнутым числом", () => {
    expect(refusalOf(z.number(), Number.NaN)).toBe(
      "Неверный ввод: ожидалось число, получено NaN",
    );
  });

  it("строка вместо числа и число вместо строки называют оба типа по-русски", () => {
    expect(refusalOf(z.number(), "12")).toBe("Неверный ввод: ожидалось число, получено строка");
    expect(refusalOf(z.string(), 12)).toBe("Неверный ввод: ожидалось строка, получено число");
  });

  it("объявления этого приложения называют свой тип по-русски: признак, объект, набор полей", () => {
    expect(refusalOf(z.boolean(), "да")).toBe(
      "Неверный ввод: ожидалось логическое значение, получено строка",
    );
    expect(refusalOf(z.object({ name: z.string() }), 12)).toBe(
      "Неверный ввод: ожидалось объект, получено число",
    );
    expect(refusalOf(z.record(z.string(), z.number()), [])).toBe(
      "Неверный ввод: ожидалось набор полей, получено массив",
    );
  });

  it("испорченный файл называет по-русски и полученное: признак, объект, пустоту, нехватку поля", () => {
    expect(refusalOf(z.string(), true)).toBe(
      "Неверный ввод: ожидалось строка, получено логическое значение",
    );
    expect(refusalOf(z.string(), {})).toBe("Неверный ввод: ожидалось строка, получено объект");
    expect(refusalOf(z.array(z.string()), null)).toBe(
      "Неверный ввод: ожидалось массив, получено пустое значение",
    );
    expect(refusalOf(z.object({ name: z.string() }), {})).toBe(
      "Неверный ввод: ожидалось строка, получено отсутствие значения",
    );
  });

  it("тип вне применения этого приложения остаётся словом словаря, а не рушит разбор", () => {
    // bigint не объявлен ни одним полем, и принести его не может ни один файл: JSON такого не
    // возит. Перевода для него нет — а разбор всё равно обязан вернуть причину, а не упасть.
    // Проверены обе стороны фразы — и ожидаемый, и полученный тип, — раз словарь у них общий.
    expect(refusalOf(z.bigint(), "12")).toBe("Неверный ввод: ожидалось bigint, получено строка");
    expect(refusalOf(z.string(), 1n)).toBe("Неверный ввод: ожидалось строка, получено bigint");
  });

  it("число вне предела называет тип по-русски: включительно и исключительно", () => {
    expect(refusalOf(z.number().max(20), 21)).toBe(
      "Слишком большое значение: ожидалось, что число будет <=20",
    );
    expect(refusalOf(z.number().lt(20), 20)).toBe(
      "Слишком большое значение: ожидалось, что число будет <20",
    );
    expect(refusalOf(z.number().min(3), 2)).toBe(
      "Слишком маленькое значение: ожидалось, что число будет >=3",
    );
    expect(refusalOf(z.number().gt(0), 0)).toBe(
      "Слишком маленькое значение: ожидалось, что число будет >0",
    );
  });

  it("целое без предела вне безопасного диапазона называет тип «целое число» по-русски", () => {
    expect(refusalOf(z.number().int(), 1e21)).toBe(
      "Слишком большое значение: ожидалось, что целое число будет <=9007199254740991",
    );
  });

  it("короткая строка называет предел символами — единственное число ровно на единице", () => {
    expect(refusalOf(z.string().min(1), "")).toBe(
      "Слишком маленькое значение: ожидалось, что строка будет иметь >=1 символ",
    );
  });

  it("предел строки во множественном числе: 2–4 и 5+ считаются разными русскими окончаниями", () => {
    expect(refusalOf(z.string().min(3), "a")).toBe(
      "Слишком маленькое значение: ожидалось, что строка будет иметь >=3 символа",
    );
    expect(refusalOf(z.string().min(5), "a")).toBe(
      "Слишком маленькое значение: ожидалось, что строка будет иметь >=5 символов",
    );
    expect(refusalOf(z.string().min(11), "a")).toBe(
      "Слишком маленькое значение: ожидалось, что строка будет иметь >=11 символов",
    );
  });

  it("короткий список называет предел элементами, не символами", () => {
    expect(refusalOf(z.array(z.string()).min(1), [])).toBe(
      "Слишком маленькое значение: ожидалось, что массив будет иметь >=1 элемент",
    );
  });

  it("предел типа вне схем этого приложения называет тип сырым словом словаря, без единицы счёта", () => {
    // bigint здесь не объявляется ни у одного поля: словарь не переводит его и не приписывает
    // единицу счёта — предел называется как у числа, только другим словом.
    expect(refusalOf(z.bigint().min(5n), 1n)).toBe(
      "Слишком маленькое значение: ожидалось, что bigint будет >=5",
    );
  });

  it("причина, для которой ru-словарь zod уже полностью русский, отдана ему как есть", () => {
    expect(refusalOf(z.enum(["a", "b"]), "c")).toBe('Неверный вариант: ожидалось одно из "a"|"b"');
  });
});
