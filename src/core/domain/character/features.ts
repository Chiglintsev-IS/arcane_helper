/**
 * Особенность — то, чем персонаж располагает по происхождению: видом, предысторией, классом.
 *
 * Игрового окончания у неё нет: то, что кончается сроком, — действующий эффект, а то, что тратится
 * и возвращается отдыхом, — ресурс, и оба живут не здесь. Своих чисел особенность не хранит:
 * величину двигает вклад — тот же, которым её двигает надетая вещь.
 */

import { z } from "zod";

import { nonEmpty } from "@/core/domain/shared/schema";

const characterFeatureSchema = z.object({
  nameRu: nonEmpty,
  /** Что особенность даёт — словами источника: приложение по ним не считает ничего. */
  summaryRu: nonEmpty,
});

/** Особенности персонажа: прежнее сохранение их не знало, и пустой список честнее отказа. */
export const characterFeaturesSchema = z.array(characterFeatureSchema).default([]);
