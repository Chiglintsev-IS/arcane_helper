/**
 * Роль заклинания в бою (FR-213).
 *
 * Отдельный модуль, потому что роль читают трое: схема заклинания (какие значения допустимы), список
 * (какой значок рисовать) и фильтры (что оставить на экране). Общее место не даёт им разойтись.
 *
 * Роль хранится в данных и из них не выводится. Любая эвристика ошибается на «Поглощении стихий»: у
 * него в данных есть урон, а по смыслу оно чисто защитное — отправив его в атаку, приложение спрячет
 * реакцию именно тогда, когда игрок ищет, чем закрыться.
 */

import type { Spell } from "@/data/schemas/spell";

export const COMBAT_ROLES = ["offense", "defense", "other"] as const;

export type CombatRole = (typeof COMBAT_ROLES)[number];

/**
 * Роль заклинания. Молчание данных читается как «другое», а не как «боевое»: предположить атаку —
 * значит поставить защитное заклинание под чужой фильтр, а это худшая из двух ошибок (FR-213).
 */
export function combatRoleOf(spell: Spell): CombatRole {
  return spell.combatRole ?? "other";
}

/** Роли, которые вообще встречаются в списке: фильтр без единой находки не показывается (FR-002). */
export function rolesPresent(spells: readonly Spell[]): Set<CombatRole> {
  return new Set(spells.map(combatRoleOf));
}
