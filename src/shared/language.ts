/**
 * Русская морфология и слова правил для текстов, которые приложение собирает само.
 *
 * Стоит собственным корнем, не внутри логики и не внутри интерфейса: фразы с числами строят обе
 * стороны — правила («2 очка заклинаний») и экран («3 раунда»), — а морфология предметной областью
 * не является и правилом игры тоже. Одна реализация вместо двух: «2 очков» за столом читается как
 * ошибка приложения, а значит и как повод сомневаться в его числах.
 *
 * Слово правил живёт здесь по той же причине: сокращение монеты и размер кости произносят и лог,
 * и значок строки, и вторая таблица разошлась бы с первой молча.
 */

/** Форма слова при числе: 1 очко, 2 очка, 5 очков. */
export function plural(count: number, forms: [string, string, string]): string {
  const remainder100 = Math.abs(count) % 100;
  const remainder10 = remainder100 % 10;
  if (remainder100 > 10 && remainder100 < 20) return forms[2];
  if (remainder10 > 1 && remainder10 < 5) return forms[1];
  if (remainder10 === 1) return forms[0];
  return forms[2];
}

/** Число вместе со словом: `withPlural(2, ["очко", "очка", "очков"])` → «2 очка». */
export function withPlural(count: number, forms: [string, string, string]): string {
  return `${count} ${plural(count, forms)}`;
}

/**
 * Модификатор со знаком: «+8», «−2».
 *
 * Здесь, а не в подписях: одно и то же число печатают лист персонажа, значок строки списка,
 * объявление мастеру и блок концентрации. Минус типографский — дефис в этой позиции на узком
 * экране читается как перенос строки.
 */
export function signed(value: number): string {
  return value < 0 ? `−${Math.abs(value)}` : `+${value}`;
}

