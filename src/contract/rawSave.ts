/**
 * Сырое сохранение: содержимое хранилища как есть, готовое к отдаче игроку.
 *
 * Едет текстом, а не разобранными полями. Разбор — это ровно то, что отказало, когда сохранение не
 * прочиталось, и договор, требующий схемы, отдавал бы копию только тогда, когда она не нужна.
 * Форму текста знает лишь тот, кто его читает руками, — сам игрок.
 *
 * Имя файла приходит отсюда же: в нём стоит дата, а даты у показывающего нет — время ставит ядро.
 */

import { z } from "zod";

export const rawSaveSchema = z
  .object({
    /** Имя файла копии. Отличается от имени выгрузки: загрузкой такая копия не принимается. */
    fileName: z.string().min(1),
    /** Содержимое хранилища текстом: скачивают и кладут в буфер именно его. */
    text: z.string().min(1),
  })
  .nullable();

/** `null` — копировать нечего: хранилище не отдало содержимого. */
export type RawSave = z.infer<typeof rawSaveSchema>;
