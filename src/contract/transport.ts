/**
 * Провод: единственное, чем игра в одиночку отличается от игры с сервером.
 *
 * Возит `unknown` в обе стороны намеренно. Провод не знает ни команд, ни снимков — знай он их, он
 * стал бы вторым местом, где объявлен договор, и разошёлся бы с первым. Разбирает привезённое
 * клиент, схемами договора.
 */

export type Transport = {
  read(): Promise<unknown>;
  send(command: unknown): Promise<unknown>;
  ask(question: unknown): Promise<unknown>;
};
